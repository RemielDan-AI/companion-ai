"""名字与实体的**统一**识别口径。

## 为什么单独抽出来

2026-10-15 梳理发现，"名字"这件事在四处各写了一套，而且**标准不一致**：

    engine/retrieve.py: keywords()        检索切词（二元组）
    engine/retrieve.py: known_names()     认专名（取 2–4 字）
    cognition/extract.py: _enrich_relation()  建一跳锚点  叫(名字{2,4})
    cognition/memory.py: link_by_entity()     建记忆关联  叫(名字{2,3})

后果不是"抓不到"而是**抓出错的前缀**（实测）：

    '公司叫工业软件公司'          ← 正确名字是「工业软件公司」
      {2,3} → ['工业软']           ← 假实体
      {2,4} → ['工业软件']         ← 假实体

这些假实体会被拿去**建链**和**当一跳锚点**，比没有还糟。

## 为什么不能只把上限改大

光把 `{2,3}` 改成 `{2,12}` 会在**没有标点**时过抓：

    '我妹妹叫林小雨她在读大学'  →  叫(林小雨她在读大学)   ← 整串都吞了

所以还要**在常见的非名字字上收尾**（`_TRIM_AT`）。
名字至少 2 字，所以前两字永不裁剪（保护「在熙」这类名字里的常见字）。
"""
from __future__ import annotations

import re

# 名字长度界限。下限 2（中文名字最少两字）；
# 上限给到 12：机构名会很长（「工业软件公司」6 字、「XX科技股份有限公司」10 字）。
# ⚠ 三处必须用同一套，否则又会出现"假实体"。
NAME_MIN = 2
NAME_MAX = 12

# 「叫XX」的原始抓取：先尽量抓长，再靠 `trim_name` 收尾。
_CALLED_RE = re.compile(rf"叫([\u4e00-\u9fff]{{{NAME_MIN},{NAME_MAX}}})")

# 收尾用的"基本不是名字内部"的字。
# 为什么需要：用户可能不写标点，`{2,12}` 会把后面的谓语一起吞掉。
# 只在**第 3 个字起**判断，所以「在熙」「是小」这类名字不会被误裁。
#
# ⚠ 这张表必须**保守**：实测第一版把「有/学/上/读」也放进来，结果
#   「公司叫北京字节跳动科技有限公司」被裁成「北京字节跳动科技」（栽在「有」上）。
#   所以只收"几乎不会出现在机构名/人名里、却常紧跟名字"的虚词。
#   下面这些**故意不收**（它们在真实名字里很常见）：
#     有（有限公司） 学（大学/学院） 上（上海） 研（研究所）
#     读（读书郎）   来（来福士）   做/住/看/听/写/吃/喝/买
_TRIM_AT = frozenset(
    "在是了也就都和跟还又要会能"
    "说想把她他它我你您这那哪什么怎"
    "的"          # 「的」是强边界：机构名里几乎不出现，却常紧跟名字
    "对"          # 「对XX过敏」这类谓语里的「对」，几乎不在名字里
)

# 句子开头的主体标记：以这些开头的**是事实句，不是名字**。
# 实测 `known_names()` 收进过「用户对芒果过敏」——
# 而 `keywords()` 会把"已知名字"整词挖掉，整句被当名字就会毁掉二元组。
_SUBJECT_PREFIXES = ("用户", "对方", "我", "你", "他", "她", "它")

# `is_name_like` **专用**的更严集合：真名字里不会出现这些**命名动词**。
# ⚠ 故意**不并进 `_TRIM_AT`**：`trim_name()` 共用 `_TRIM_AT` 做收尾边界，
#   而「公司叫工业软件公司」正是靠它抓到长名字的——把「叫」放进去，
#   `trim_name` 会在索引 2 处截断成「公司」，把之前修好的长机构名又弄坏。
#   实测踩坑：`known_names()` 收进过「妹妹叫林小雨」（`对方`前缀被剥掉后），
#   而 `keywords()` 会把"已知名字"整词挖掉 → 双元组被毁。
#
# ⚠ 这批是**实测补的**：`known_names()` 收进过
#   「林小雨**不吃**香菜」「林小雨**怕**狗」这种**整句事实**当实体，
#   于是图遍历把它们当成节点去走（`走到=['妹妹','林小雨不吃香菜',…]`）。
#   ⚠ 只放**绝不会出现在名字/机构名里**的字：
#     `学`（大学）`上`（上海/上学的地方）`工`（工业）`有`（有限公司）
#     `来`/`去`（来福这种宠物名）一律**不能放**——放进去会把
#     「广州大学」「北京字节跳动科技有限公司」这种正常名字也毙掉。
_NOT_IN_NAME = frozenset("叫不没别吃喝怕养住买卖睡玩用走跑") | _TRIM_AT

# 不带括号的片段（整句事实常常是这种）额外限长：
# 真名字很少超过 6 字，而"整句事实"通常一长串。
# 带括号的（`北京字节跳动科技有限公司（单位）`）仍可到 NAME_MAX。
BARE_NAME_MAX = 6


def trim_name(name: str) -> str:
    """把"吞进来的谓语/虚词"裁掉。前两字永不裁剪（名字至少两字）。"""
    text = str(name or "")
    for i in range(NAME_MIN, len(text)):
        if text[i] in _TRIM_AT:
            return text[:i]
    return text


def find_called_names(text: str) -> list[str]:
    """从「叫XX」里取名字。**不截断**（这正是原来 `{2,3}` 的 bug）。"""
    out: list[str] = []
    for m in _CALLED_RE.finditer(str(text or "")):
        name = trim_name(m.group(1))
        if NAME_MIN <= len(name) <= NAME_MAX and name not in out:
            out.append(name)
    return out


# `名字（关系）` —— 一跳锚点的形态。extract 负责产出、retrieve 负责解析，
# 两边必须用同一个正则（原来 retrieve 侧写死 `{2,4}`，会把「工业软件公司」
# **静默截断**成「软件公司」，锚点就歪了）。
PAIR_RE = re.compile(rf"([\u4e00-\u9fff]{{{NAME_MIN},{NAME_MAX}}})（([^）]+)）")


def is_name_like(part: str) -> bool:
    """这段文字像不像一个名字/实体。

    ⚠ 光看「纯中文 + 长度在界内」**不够**：那会把整句事实也当成名字——
    实测 `known_names()` 一次收进了「林小雨不能吃花生」这种**整句**，
    而 `keywords()` 的"整词切出并挖掉"是为**短专名**设计的：
    把整句当名字 → 整段文本被挖成空白 → 二元组全毁 →
    查询与目标两边都只剩整句 token → **零重合、分数 0、一跳失效**。

    所以补一条：**真名字里不含虚词/谓语**（`_TRIM_AT` 那批字）。
    代价：含「在」「是」的人名（如「在熙」）会被判成不像名字——可接受。
    """
    text = str(part or "").strip("） 　(")
    if not (NAME_MIN <= len(text) <= NAME_MAX):
        return False
    if not all("\u4e00" <= ch <= "\u9fff" for ch in text):
        return False
    if any(text.startswith(p) for p in _SUBJECT_PREFIXES):
        return False          # 以主体开头的多半是事实句（「用户对芒果过敏」）
    return not any(ch in _NOT_IN_NAME for ch in text)
