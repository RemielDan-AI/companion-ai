def main() -> int:
    bad: list[tuple[str, bool, bool, str]] = []
    for text, expect, why in CASES:
        got = self_refused(text)
        mark = "✅" if got == expect else "✗"
        if got != expect:
            bad.append((text, expect, got, why))
        print(f"  {mark} 期望={str(expect):<5} 实际={str(got):<5} {why}")
        print(f"       「{text[:56]}」")
    print()
    if bad:
        print(f"✗ {len(bad)} 项不符：")
        for text, expect, got, why in bad:
            print(f"   {why}：期望 {expect} 实际 {got}　「{text[:50]}」")
        return 1
    n_ref = sum(1 for _, e, _ in CASES if e)
    print(f"✅ 全部正确（{n_ref} 条应算拒绝、{len(CASES) - n_ref} 条不该算）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
