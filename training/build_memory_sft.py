# **长短拉伸**（2026-10-20 用户要求："把话长度变得随机一点，同一个问题时短时长"）
#
# 问题：129 个问题里 **62 个**的三种说法长度差 ≤4 字 —— 模型学到的是
#   "这个问题永远差不多长"，所以实测 v1.5 回复 v1.3 从 21.9 字涨到 29.5 字且**方差很小**。
#
# 做法：把同一题的几种说法**按长度排好**，再朝两头拉：
#   · 最短的那条 → 砍到**第一个分句**（核心答案）
#   · 最长的那条 → 加一句**暖尾巴**（"这个我记着呢"这类）
#
# ⚠ **两条安全线**（不然就是在造错误训练数据）：
#   ① 砍分句是**取子集**，不会凭空造事实；
#   ② 暖尾巴是**纯语气词**，不带任何新事实（`WARM_TAILS` 里都是这种）。
#   所以拉伸前后**事实完全一致**，只是长短不同。
# ---------------------------------------------------------------------------
_SPLIT_AT = ("，", "。", "——", "：", "；", "、", ",")

# 暖尾巴：**只表达"我记着"，不添加任何事实**
# ⚠ 暖尾巴里**不许出现「你」**：主语校验会把它误判成把别人的事说成用户的
#   （实测正踩过：「…三样：花生过敏，香菜和辣都不吃。**你**说过的」被判串人）。
WARM_TAILS = ("这个我记着呢。", "我记住了。", "这个我记得。", "我记着的。")
# 已经有下面这些味道的，就不再补暖尾巴（免得叠成两遍）
_ALREADY_WARM = ("记着", "记得", "记住了", "你说过", "我记")


def short_form(gold: str) -> str:
    """取第一个分句（核心答案）。取不出就原样返回。"""
    text = str(gold or "").strip()
    cut = len(text)
    for mark in _SPLIT_AT:
        i = text.find(mark)
        if 0 < i < cut:
            cut = i
    short = text[:cut].strip()
    # 太短（<2 字）或会丢主语标示时，不硬砍
    return short if len(short) >= 2 else text


def long_form(gold: str, seed_text: str = "") -> str:
    """在原文后面补一句暖尾巴（不添加事实）。"""
    text = str(gold or "").strip()
    if any(w in text for w in _ALREADY_WARM):
        return text
    tail = WARM_TAILS[sum(ord(c) for c in (seed_text or text)) % len(WARM_TAILS)]
    if text.endswith(("。", "！", "？")):
        return text + tail
    return text + "。" + tail


def stretch(golds: list[str], seed_text: str = "") -> list[str]:
    """把一组说法拉成 **短 / 中 / 长** 三条。

    ⚠⚠ **2026-10-20 返工：不再加暖尾巴。**
      第一版给"长版本"统一补一句「这个我记着呢」，用户当场指出
      **"感觉说话可能会更像 AI 了，可能是说话内容太过于模板化"** —— 说得对：
      每个长答案都挂同一句固定尾巴，等于在教它**背口头禅**，
      这比"话长"严重得多（助手腔就是这么来的）。
      → 现在**只往短拉**（截取子集，永远不会模板化）；
        "长"那一档直接用**已有的真实说法**，一个字都不加。
      代价：长度方差比第一版小，但**不新增任何模板**。
    """
    items = [str(g or "").strip() for g in golds if str(g or "").strip()]
    if not items:
        return []
    items.sort(key=len)
    short = short_form(items[0])
    mid = items[len(items) // 2]
    long_ = items[-1]
    seen: set[str] = set()
    uniq: list[str] = []
    for g in (short, mid, long_):
        if g not in seen:
            seen.add(g)
            uniq.append(g)
    return uniq or items[:3]

def _utterance(content: str) -> str:
    """把库里的 `对方…` 事实反推成"用户当时说的那句话"，用来建情景。

    ⚠ **必须有这一步**（2026-10-19 实测踩坑）：组装层算置信度时，接地是拿
      **这条记忆来源情景的原话**（`source_episodic`）比的。直接 `upsert_semantic`
      不链情景的话，它会退化成拿**当前提问**去比 → 几乎全部低置信 → **块是空的**。
      生产里每条事实都链到"用户说那句话的那轮"，这里要一致。
    """
    import re
    c = str(content or "")
    if c.startswith("对方提到的人："):
        body = c[len("对方提到的人："):]
        m = re.match(r"(.+?)（(.+?)）", body)
        if m:
            return f"{m.group(1)}是{m.group(2)}"
        return f"我提过{body}"
    if c.startswith("对方"):
        return "我" + c[2:]
    return c



